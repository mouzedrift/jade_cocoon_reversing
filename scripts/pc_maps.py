"""PC build: the map code of src/maps/NAME.c (and its data, src/maps/data/NAME.c), with a table of where the PlayStation had each of its names
(they carry the address: events_800B4298), so that the addresses event scripts and GAME use for map code and
data (PSX_PTR, MAP_CODE_CALL) find them (src/pc/mapcode.c).

usage: pc_maps.py OUT_DIR SRC...   writes OUT_DIR/map_NAME_pc.c per source and OUT_DIR/maps_pc.c (the list)
"""
import os
import re
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))


def file_ids():
    out = {}
    for line in open(os.path.join(REPO, "src", "enums.h")):
        m = re.match(r"\s*SCENE_(\w+)_SBH = (\d+)u", line)
        if m:
            out[m.group(1).lower()] = int(m.group(2))
    return out


def main(argv):
    out_dir, srcs = argv[0], argv[1:]
    ids = file_ids()
    names = []
    for src in srcs:
        name = os.path.basename(src)[:-2]
        data = os.path.join(os.path.dirname(src), "data", name + ".c")
        has_data = os.path.exists(data)
        text = (open(data).read() if has_data else "") + open(src).read()
        syms = {}
        for m in re.finditer(r"^[A-Za-z_][\w \*]*?\b(\w+_(800[BC][0-9A-F]{4}))\s*(\(|\[|=|;)", text, re.M):
            sym, addr, kind = m.group(1), int(m.group(2), 16), m.group(3)
            if sym in syms:
                continue
            is_fn = kind == "(" and re.search(r"^[^\n]*\b%s\([^;]*\)\s*\n\{" % sym, text, re.M) is not None
            if kind == "(" and not is_fn:
                continue  # a prototype
            syms[sym] = (addr, is_fn)
        lines = ["/* generated by scripts/pc_maps.py from src/maps/%s.c */" % name]
        lines += ["#define REF_%s 0x%08X" % (s, a) for s, (a, _) in sorted(syms.items(), key=lambda x: x[1][0])]
        lines += (['#include "maps/data/%s.c"' % name] if has_data else []) + ['#include "maps/%s.c"' % name, '#include "pc/mapcode.h"', "",
                  "static const PcMapSym syms[] = {"]
        for s, (a, fn) in sorted(syms.items(), key=lambda x: x[1][0]):
            lines.append("    { 0x%08X, %s, (void*)%s }," % (a, "0" if fn else "sizeof(%s)" % s, s if fn else "&" + s))
        lines += ["};", "const PcMap pcMap_%s = { %d, \"%s\", syms, sizeof(syms) / sizeof(syms[0]) };" % (name, ids[name], name), ""]
        path = os.path.join(out_dir, "map_%s_pc.c" % name)
        text = "\n".join(lines)
        if not os.path.exists(path) or open(path).read() != text:
            open(path, "w").write(text)
        names.append(name)
    lines = ['#include "pc/mapcode.h"'] + ["extern const PcMap pcMap_%s;" % n for n in names]
    lines += ["const PcMap* const pcMaps[] = {"] + ["    &pcMap_%s," % n for n in names] + ["    0,", "};", ""]
    path = os.path.join(out_dir, "maps_pc.c")
    text = "\n".join(lines)
    if not os.path.exists(path) or open(path).read() != text:
        open(path, "w").write(text)


if __name__ == "__main__":
    main(sys.argv[1:])
