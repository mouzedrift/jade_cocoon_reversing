#!/usr/bin/env python3
"""
Build the whole game-code area of the executable, mixing decompiled C and generated assembly.

  * every function marked "// Matched" in src/*.c is compiled from C,
  * every other function in the game code range is taken from the original executable
    (scripts/gen_asm.py) and pulled in as inline assembly,
  * all of it is emitted in address order into one generated C file, so the linked result
    puts each function at its real address.

The result (build_psyq/full.exe) can then be compared against the original executable:
the closer the two are, the more of the game is understood.

usage: full_build.py SLUS_008.54   (run build.py first, it is used to check which functions match)
"""
import glob
import os
import re
import subprocess
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_asm  # noqa: E402
from check_match import Checker  # noqa: E402

LIBS = ("libapi", "libgte", "libmcrd", "libcard", "libcd", "libc2", "libds", "libetc", "libgpu", "libmath",
        "libpad", "libpress", "libsnd", "libsn", "libspu", "libmcx")
BUILD = os.path.join(REPO, "build_psyq")
PSYQ = os.path.join(REPO, "libs", "psyq4.4")


def wine(cmd):
    return ["wine"] + cmd if sys.platform.startswith("linux") else cmd


def run(cmd, **kw):
    r = subprocess.run(wine(cmd), stdout=subprocess.PIPE, stderr=subprocess.STDOUT, **kw)
    if r.returncode != 0:
        sys.stdout.write(r.stdout.decode(errors="replace"))
        sys.exit("command failed: %s" % " ".join(cmd))
    return r.stdout.decode(errors="replace")

# ----------------------------------------------------------------------------
# splitting the C sources into top-level blocks

SIG = re.compile(r"^[A-Za-z_][\w \*]*?\b(\w+)\(.*\)\s*$")


def split_blocks(text):
    """returns [(kind, name, text)] with kind in 'func', 'other'; comments stay with the next block"""
    lines = text.split("\n")
    blocks = []
    cur = []
    depth = 0
    i = 0
    while i < len(lines):
        ln = lines[i]
        cur.append(ln)
        depth += ln.count("{") - ln.count("}")
        i += 1
        if depth == 0 and cur and cur[-1].strip() and (cur[-1].rstrip().endswith((";", "}")) or cur[-1].startswith("#")):
            blocks.append(cur)
            cur = []
        elif depth == 0 and cur and not cur[-1].strip() and all(not l.strip() for l in cur):
            cur = []
    if cur:
        blocks.append(cur)
    out = []
    for b in blocks:
        body = [l for l in b if l.strip() and not l.strip().startswith("//")]
        name = None
        if len(body) >= 2 and body[1].strip() == "{" and SIG.match(body[0]):
            name = SIG.match(body[0]).group(1)
        out.append(("func" if name else "other", name, "\n".join(b).strip("\n"),
                    any(l.strip() == "// Matched" for l in b)))
    return out

# ----------------------------------------------------------------------------

def asm_block(path):
    lines = open(path).read().rstrip("\n").split("\n")
    body = "\n".join('    "%s\\n"' % l.replace("\\", "\\\\").replace('"', '\\"') for l in lines)
    return "asm(\n%s);" % body.lstrip()


def main():
    exe_path = sys.argv[1]
    exe = open(exe_path, "rb").read()[0x800:]
    syms = gen_asm.load_symbols(REPO)
    code = [(a, n) for a, n in syms if gen_asm.BASE <= a < gen_asm.CODE_END]
    names = {a: n for a, n in syms}
    from capstone import Cs, CS_ARCH_MIPS, CS_MODE_MIPS32, CS_MODE_LITTLE_ENDIAN
    md = Cs(CS_ARCH_MIPS, CS_MODE_MIPS32 + CS_MODE_LITTLE_ENDIAN)

    # only functions that really match (according to the normal build) are taken from C,
    # anything else would shift every following function
    chk = Checker(exe_path, REPO)
    verified = {n for n in chk.map if chk.check(n) == 0}
    built_size = {}
    for n, a in chk.map.items():
        nxt = [x for x in chk.map_addrs if x > a]
        built_size[n] = (nxt[0] - a) if nxt else 0

    c_funcs = {}
    others = []
    seen_includes = set()
    order = ["main.c", "funcs.c", "sound.c", "globals.c"]
    for fn in order:
        for kind, name, text, matched in split_blocks(open(os.path.join(REPO, "src", fn)).read()):
            if kind == "func":
                if matched and name in verified:
                    c_funcs[name] = text
                continue
            if text.startswith("#include"):
                if text in seen_includes:
                    continue
                seen_includes.add(text)
            others.append(text)

    parts = ["/* generated by scripts/full_build.py, do not edit */"]
    parts += others
    n_c = n_asm = n_tail = 0
    for (a, n), (b, _) in zip(code, code[1:] + [(gen_asm.CODE_END, "")]):
        if n in c_funcs and built_size.get(n, 1 << 30) <= b - a:
            parts.append(c_funcs[n])
            n_c += 1
            if built_size[n] < b - a:
                # the symbol list is incomplete: bytes behind the decompiled part belong to
                # functions that have no symbol yet, keep them as raw data
                tail = gen_asm.emit_function(md, exe, n + "_tail", a + built_size[n], b - a - built_size[n], names)
                parts.append("asm(\n" + "\n".join('    "%s\\n"' % l.replace("\\", "\\\\").replace('"', '\\"')
                                                    for l in tail.rstrip("\n").split("\n")).lstrip() + ");")
                n_tail += 1
        else:
            if n.startswith(gen_asm.DATA_PREFIXES):
                text = gen_asm.emit_data(exe, n, a, b - a)
            else:
                text = gen_asm.emit_function(md, exe, n, a, b - a, names)
            parts.append("asm(\n" + "\n".join('    "%s\\n"' % l.replace("\\", "\\\\").replace('"', '\\"')
                                                for l in text.rstrip("\n").split("\n")).lstrip() + ");")
            n_asm += 1
    os.makedirs(BUILD, exist_ok=True)
    src = os.path.join(BUILD, "full.c")
    open(src, "w").write("\n\n".join(parts) + "\n")
    print("generated full.c: %d C functions (%d with an asm tail), %d asm functions" % (n_c, n_tail, n_asm))

    bin_dir = os.path.join(PSYQ, "bin")
    inc = ["-I", os.path.join(PSYQ, "INCLUDE"), "-I", os.path.join(REPO, "src")]
    pre = os.path.join(BUILD, "full.preproc")
    cc = os.path.join(BUILD, "full.o")
    obj = os.path.join(BUILD, "full.obj")
    cpp_args = ["-undef", "-D__GNUC__=2", "-v", "-D__OPTIMIZE__"] + inc + [
        "-lang-c", "-Dmips", "-D__mips__", "-D__mips", "-Dpsx", "-D__psx__", "-D__psx", "-D_PSYQ",
        "-D__EXTENSIONS__", "-D_MIPSEL", "-D__CHAR_UNSIGNED__", "-D_LANGUAGE_C", "-DLANGUAGE_C", src, pre]
    run([os.path.join(bin_dir, "CPPPSX.EXE")] + cpp_args)
    run([os.path.join(bin_dir, "CC1PSX.EXE"), "-quiet", "-G0", "-O2", pre, "-o", cc])
    run([os.path.join(bin_dir, "ASPSX.EXE"), "-G0", "-q", cc, "-o", obj])

    cmd = os.path.join(BUILD, "full_link.txt")
    cpe = os.path.join(BUILD, "full.cpe")
    addr_of = {n: a for a, n in syms}
    equs = {}
    for _ in range(4):
        with open(cmd, "w") as f:
            # the original has .text first, then .rdata, .data and .bss
            f.write("\torg\t$80010000\n")
            f.write("text\tgroup\n")
            f.write("rdata\tgroup\n")
            f.write("data\tgroup\n")
            f.write("bss\tgroup\tbss\n")
            f.write("\tsection\t.text,text\n")
            f.write("\tsection\t.rdata,rdata\n")
            f.write("\tsection\t.data,data\n")
            f.write("\tsection\t.sdata,data\n")
            f.write("\tsection\t.sbss,bss\n")
            f.write("\tsection\t.bss,bss\n")
            f.write('\tinclude "%s"\n' % obj)
            for n, a in sorted(equs.items()):
                f.write("%s\tequ\t$%08x\n" % (n, a))
            for lib in LIBS:
                f.write('\tinclib "%s.lib"\n' % lib)
        r = subprocess.run(wine([os.path.join(bin_dir, "psylink.exe"), "/l", os.path.join(PSYQ, "LIB"), "/c", "/n",
                                 "4000", "/q", "/m", "@" + cmd + "," + cpe + "," + os.path.join(BUILD, "full.sym") +
                                 "," + os.path.join(BUILD, "full.map")]),
                           stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        out = r.stdout.decode(errors="replace")
        missing = set(re.findall(r"Symbol '(\w+)' not defined", out))
        if r.returncode == 0:
            break
        def addr_for(m):
            if m in addr_of:
                return addr_of[m]
            g = re.fullmatch(r"\w*?_?([0-9A-Fa-f]{8})", m)  # sub_XXXXXXXX style names carry their address
            return int(g.group(1), 16) if g else None
        new = {m: addr_for(m) for m in missing if addr_for(m) is not None and m not in equs}
        if not new:
            sys.stdout.write(out)
            sys.exit("link failed")
        equs.update(new)
    else:
        sys.exit("link failed")
    if equs:
        print("symbols defined by address in the link script:", ", ".join(sorted(equs)))
    run([os.path.join(bin_dir, "cpe2exe.exe"), "-CA", cpe])

    built = open(os.path.join(BUILD, "full.exe"), "rb").read()[0x800:]
    total = (gen_asm.CODE_END - gen_asm.BASE) // 4
    diff = 0
    for i in range(0, total * 4, 4):
        if exe[i:i + 4] != built[i:i + 4]:
            diff += 1
    print("game code: %d / %d words identical to the original" % (total - diff, total))
    return 0


if __name__ == "__main__":
    sys.exit(main())
